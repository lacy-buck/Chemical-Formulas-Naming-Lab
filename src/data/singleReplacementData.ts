export interface ReactionSpecies {
  formula: string; // Chemical formula with subscripts, e.g. "Mg", "HCl", "MgCl₂", "H₂"
  coefficient: number; // Balanced lowest whole-number coefficient (e.g. 1, 2)
}

export interface SingleReplacementProblem {
  id: string;
  type: 'metal' | 'halogen';
  reactantsDisplay: string; // Strictly without coefficients, e.g. "Zn + CuSO₄", "Mg + HCl"
  singleElement: string; // "Zn" or "Cl2"
  singleElementName: string; // "Zinc" or "Chlorine"
  compoundTarget: string; // "CuSO4" or "HCl"
  compoundTargetName: string; // "Copper(II) sulfate" or "Hydrochloric acid"
  targetIonReplaced: string; // "Cu" or "H"
  targetIonName: string; // "Copper" or "Hydrogen"
  doesReact: boolean;
  activityComparison: string; // e.g., "Zn is higher than Cu on the activity series (Zn > Cu)"
  productsDisplay: string; // e.g. "ZnSO₄ + Cu" or "No Reaction (NR)"
  standardBalancedEquation: string; // e.g. "Zn + CuSO₄ → ZnSO₄ + Cu" or "Cu + 2HCl → No Reaction"
  
  // Species for Step 2 balancing (only relevant when doesReact is true)
  reactantsSpecies: ReactionSpecies[];
  productsSpecies: ReactionSpecies[];
  
  acceptedProductForms: string[]; // Variations for Step 1 products box
  explanationSteps: string[];
}

